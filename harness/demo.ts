/** Evidence demo (no model needed): writes results/demo/*.
 *  - a generated code patch + an independently run unittest (sandboxed Python)
 *  - a sourced short text passage from the pinned glossary snapshot
 *  - a Plicastratum fold/unfold trace over certified macros
 *  - a non-mutating clock9:// address roundtrip
 *  - the full clock trace of the solve */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { HybridSolver } from '../src/solver.js';
import { fold, unfold, foldWitness } from '../src/listops/macros.js';
import { fromDsl, toDsl, canonical } from '../src/listops/ast.js';
import { address, resolve } from '../src/address.js';
import { GlossaryGenerator, type Snapshot } from '../src/text/glossary.js';
import { PythonSandbox } from './executor.js';
import { loadListOps, trainPairs, ROOT } from './tasks.js';

const out = path.join(ROOT, 'results', 'demo');
mkdirSync(out, { recursive: true });
const all = loadListOps();
const sandbox = new PythonSandbox();
const solver = new HybridSolver({ grammar: true, cache: true, executor: sandbox, train: trainPairs(all) });

// 1. code patch + independent test
const task = all.find(t => t.id === 'para-000')!;
const r = await solver.solve(task);
if (!r.code) throw Error('demo task unexpectedly refused');
const fn = r.code.replace('def solve(', 'def total_even_squares(');
const added = [...fn.trimEnd().split('\n'), ''];
const patch = [
  '--- a/examples/listops_solutions.py', '+++ b/examples/listops_solutions.py', `@@ -1,2 +1,${2 + added.length} @@`,
  ' """Solutions generated by CLOCK9 (grammar path); every function is test-gated."""', ' ',
  ...added.map(l => '+' + l),
].join('\n') + '\n';
const testSrc = `import unittest\n\n${fn}\n\nclass T(unittest.TestCase):\n    def test_hidden(self):\n        cases = ${JSON.stringify(task.hidden.map(h => [h.input, h.output]))}\n        for xs, want in cases:\n            self.assertEqual(total_even_squares(xs), want)\n\nunittest.main(argv=["t"], exit=True)\n`;
const tr = await sandbox.runProgram(testSrc);
writeFileSync(path.join(out, 'patch.diff'), patch);
writeFileSync(path.join(out, 'test_listops_patch.py'), testSrc);
writeFileSync(path.join(out, 'patch-test-result.json'), JSON.stringify({ task: task.id, prompt: task.prompt, resolvedBy: r.resolvedBy, dsl: r.dsl, sandbox: sandbox.id, unittest: tr, hiddenCases: task.hidden.length }, null, 1));

// 2. sourced text passage
const snap = JSON.parse(readFileSync(path.join(ROOT, 'tasks', 'glossary_snapshot.json'), 'utf8')) as Snapshot;
const text = new GlossaryGenerator(snap).generate('Define Plicastratum');
writeFileSync(path.join(out, 'text-passage.json'), JSON.stringify(text, null, 1));

// 3. fold/unfold trace: solve a few train tasks that share words, then fold a new program
for (const t of all.filter(t => t.split === 'train').slice(0, 60)) await solver.solve(t);
const top = solver.macros[0];
if (!top) throw Error('no certified macro after 60 verified train programs');
// target = a NEW composition: the top certified word followed by two other stages
const target = { stages: [...top.body, ...fromDsl('take 2 | reverse | sum').stages], terminal: 'sum' as const };
const folded = fold(target, solver.macros);
const foldTrace = {
  library: solver.macros.slice(0, 8).map(m => ({ glyph: m.glyph, body: toDsl({ stages: m.body, terminal: 'list' }).replace(/ \| list$/, ''), witnesses: m.witnesses, certificate: m.certificate })),
  program: toDsl(target), folded: folded.stages.map(s => s.op === 'macro' ? s.glyph : toDsl({ stages: [s], terminal: 'list' }).replace(/ \| list$/, '')).join(' | ') + ` | ${folded.terminal}`,
  unfolded: toDsl(unfold(folded, solver.macros)), identity: canonical(unfold(folded, solver.macros)) === canonical(target),
  behaviourWitness: foldWitness(target, solver.macros, [[1, 2, 3, 4, 6, 8], [], [-2, -4, 5]]),
};
writeFileSync(path.join(out, 'fold-trace.json'), JSON.stringify(foldTrace, null, 1));

// 4. address roundtrip (pure)
const addr = address(fromDsl(r.dsl!));
const res = resolve(addr);
writeFileSync(path.join(out, 'address-roundtrip.json'), JSON.stringify({ address: addr, resolved: res, roundtrip: address(res.program) === addr }, null, 1));

// 5. clock trace
writeFileSync(path.join(out, 'clock-trace.json'), JSON.stringify({ task: task.id, beats: r.beats, witness: r.witness }, null, 1));
console.log(JSON.stringify({ patchTest: tr, text: text.passage, fold: foldTrace.folded, identity: foldTrace.identity, address: addr, beats: r.beats.map(b => `${b.beat}:${b.kind}/${b.source}`).join(' ') }, null, 1));
