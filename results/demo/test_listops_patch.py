import unittest

def total_even_squares(xs: list[int]) -> int:
    v = list(xs)
    v = [x * x for x in v]
    v = [x for x in v if x % 2 == 0]
    return sum(v)


class T(unittest.TestCase):
    def test_hidden(self):
        cases = [[[],0],[[0],0],[[-3,3],0],[[5,5,-2,8,1],68],[[-10,-7,4,9,2,2,6,-1],160],[[-4,-4],32],[[-2,-9,-4,0,-6,5],56],[[3],0],[[-4,8,0,-5,9,-7],80],[[10,-3,-7],100],[[9,10,4],116],[[3,6,3],36],[[-8,-6,10,-3,4],216],[[-2,6],40],[[-6,-3,-6,-10,-9,-4,-10,-1],288],[[8,-2,6,-1],104],[[-1,-9,-10,-7,3,5,9,-6],136],[[9,-4,2,-6,-6,3],92],[[0,-2,-4,7,7,7],20],[[-8,4,0,4,-4,-5,-9],112],[[7,-1],0],[[9,10,-7,4],116],[[10,-2],104],[[6,-3,-8],100],[[2,-9,4,1,-6,-3],56]]
        for xs, want in cases:
            self.assertEqual(total_even_squares(xs), want)

unittest.main(argv=["t"], exit=True)
